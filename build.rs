use std::process::Command;
use std::{
    env, fs,
    path::PathBuf,
    time::{SystemTime, UNIX_EPOCH},
};

fn main() {
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set by cargo"));
    fs::copy("linker/memory.x", out.join("memory.x")).expect("linker/memory.x is readable");
    fs::copy("linker/noinit.x", out.join("noinit.x")).expect("linker/noinit.x is readable");
    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rerun-if-changed=linker/memory.x");
    println!("cargo:rerun-if-changed=linker/noinit.x");
    println!("cargo:rerun-if-changed=Cargo.lock");
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-env-changed=SOURCE_DATE_EPOCH");

    fn locked_version(name: &str) -> Option<String> {
        let lock = fs::read_to_string("Cargo.lock").ok()?;
        let mut found = false;
        for line in lock.lines() {
            let line = line.trim();
            if line == format!("name = \"{}\"", name) {
                found = true;
            } else if found && line.starts_with("version = ") {
                return line.split('"').nth(1).map(|version| version.to_owned());
            } else if found && line.starts_with('[') {
                break;
            }
        }
        None
    }

    let commit = Command::new("git")
        .args(["rev-parse", "--short=12", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "unknown".to_owned());

    let build_time = env::var("SOURCE_DATE_EPOCH")
        .ok()
        .and_then(|s| s.parse::<u64>().ok())
        .unwrap_or_else(|| {
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map(|d| d.as_secs())
                .unwrap_or(0)
        });

    let rustc = Command::new(env::var("RUSTC").unwrap_or_else(|_| "rustc".to_owned()))
        .arg("--version")
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| {
            String::from_utf8_lossy(&o.stdout)
                .split_whitespace()
                .nth(1)
                .unwrap_or("unknown")
                .to_owned()
        })
        .unwrap_or_else(|| "unknown".to_owned());

    let mut date_cmd = Command::new("date");
    date_cmd.args(["-u", "+%Y-%m-%dT%H:%M:%SZ"]);
    if env::var_os("SOURCE_DATE_EPOCH").is_some() {
        date_cmd.args(["-d", &format!("@{}", build_time)]);
    }
    let build_date: String = date_cmd
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_else(|| build_time.to_string());

    let version = env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".to_owned());
    let embassy = locked_version("embassy-stm32").unwrap_or_else(|| "0.6".to_owned());
    let version_text = format!("{} (Rust {}, Embassy {})", version, rustc, embassy);
    let version_rs = format!(
        "// Generated by build.rs. Do not edit.\n\
         pub const VERSION: &str = {:?};\n\
         pub const VERSION_TEXT: &str = {:?};\n\
         pub const GIT_COMMIT: &str = {:?};\n\
         pub const BUILD_TIME: &str = {:?};\n\
         pub const BUILD_TIME_EPOCH: u64 = {};\n\
         pub const RUSTC_VERSION: &str = {:?};\n\
         pub const EMBASSY_VERSION: &str = {:?};\n",
        version, version_text, commit, build_date, build_time, rustc, embassy,
    );
    fs::write(out.join("version.rs"), version_rs).expect("version.rs is writable");
}
